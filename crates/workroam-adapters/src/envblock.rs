//! The per-machine block at the end of `AGENTS.md` (RULE-02) and the synced
//! "workspace sync" convention block written by `workroam init`.

use serde::{Deserialize, Serialize};

pub const ENV_BEGIN: &str = "<!-- workroam:env:begin -->";
pub const ENV_END: &str = "<!-- workroam:env:end -->";
pub const SYNC_BEGIN: &str = "<!-- workroam:sync:begin -->";
pub const SYNC_END: &str = "<!-- workroam:sync:end -->";

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct RepoEnv {
    pub name: String,
    pub mode: String,
    pub can_push: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct EnvInfo {
    pub device: String,
    pub os: String,
    pub os_version: String,
    pub shell: String,
    pub project_dir: String,
    /// Whether this machine reaches the internal network.
    pub internal_network: bool,
    pub read_only: bool,
    pub repos: Vec<RepoEnv>,
}

/// Render the machine block (bilingual, stable order so regeneration is a no-op).
pub fn render(info: &EnvInfo) -> String {
    let mut s = String::new();
    s.push_str(ENV_BEGIN);
    s.push_str("\n## 本机环境 / This machine\n\n");
    s.push_str("> 由 Workroam 在每次拉取后生成，同步时会被去掉，请不要手动修改。\n");
    s.push_str("> Generated by Workroam after every pull and stripped on push. Do not edit.\n\n");
    s.push_str(&format!("- 设备 / Device: {}\n", info.device));
    s.push_str(&format!("- 系统 / OS: {} {}\n", info.os, info.os_version).replace("  ", " "));
    if !info.shell.is_empty() {
        s.push_str(&format!("- Shell: {}\n", info.shell));
    }
    s.push_str(&format!(
        "- 项目目录 / Project dir: `{}`\n",
        info.project_dir
    ));
    s.push_str(&format!(
        "- 内网 / Internal network: {}\n",
        if info.internal_network {
            "可访问 / reachable"
        } else {
            "不可访问 / not reachable"
        }
    ));
    if info.read_only {
        s.push_str("- 只读设备：只能拉取，不能推送 / Read-only device: pull only\n");
    }
    if !info.repos.is_empty() {
        s.push_str("\n| 仓库 / Repository | 模式 / Mode | 本机能否推送 / Push from here |\n| --- | --- | --- |\n");
        for r in &info.repos {
            let push = if r.can_push {
                "能 / yes"
            } else {
                "不能，只做本地提交 / no, commit locally only"
            };
            s.push_str(&format!("| {} | {} | {} |\n", r.name, r.mode, push));
        }
    }
    s.push_str(ENV_END);
    s.push('\n');
    s
}

/// Remove the machine block (and the blank line before it).
pub fn strip(content: &str) -> String {
    match find_block(content, ENV_BEGIN, ENV_END) {
        Some((a, b)) => {
            let head = content[..a].trim_end_matches(['\n', '\r']);
            let tail = content[b..].trim_start_matches(['\n', '\r']);
            let mut out = head.to_string();
            if !out.is_empty() {
                out.push('\n');
            }
            if !tail.is_empty() {
                if !out.is_empty() {
                    out.push('\n');
                }
                out.push_str(tail);
            }
            out
        }
        None => content.to_string(),
    }
}

/// Replace or append the machine block.
pub fn apply(content: &str, block: &str) -> String {
    let base = strip(content);
    let mut out = base.trim_end_matches(['\n', '\r']).to_string();
    if !out.is_empty() {
        out.push_str("\n\n");
    }
    out.push_str(block);
    out
}

fn find_block(content: &str, begin: &str, end: &str) -> Option<(usize, usize)> {
    let a = content.find(begin)?;
    let rel = content[a..].find(end)?;
    let mut b = a + rel + end.len();
    if content[b..].starts_with("\r\n") {
        b += 2;
    } else if content[b..].starts_with('\n') {
        b += 1;
    }
    Some((a, b))
}

/// The synced convention block (init, step 4): tells every agent how to hand off.
pub fn sync_block() -> String {
    format!(
        "{SYNC_BEGIN}\n## 工作区同步 / Workspace sync\n\n\
- 本项目用 Workroam 在多台电脑之间同步。换机器前先更新 `.handoff/HANDOFF.md`，再运行 `workroam push --release --json`；到新机器后运行 `workroam pull --json` 并先读 `HANDOFF.md`。\n\
- This project is synced between computers with Workroam. Before leaving, update `.handoff/HANDOFF.md` and run `workroam push --release --json`; on arrival run `workroam pull --json` and read `HANDOFF.md` first.\n\
- 详细步骤见 Workroam Skill（`.agents/skills/workroam/SKILL.md`）。 / Details: the Workroam Skill.\n\
- `.workroam/SYNCING` 存在时不要修改项目文件。 / Do not edit files while `.workroam/SYNCING` exists.\n\
{SYNC_END}\n"
    )
}

/// Insert the convention block when missing (keeps an edited block as is).
pub fn ensure_sync_block(content: &str) -> Option<String> {
    if content.contains(SYNC_BEGIN) {
        return None;
    }
    let (body, env) = match find_block(content, ENV_BEGIN, ENV_END) {
        Some((a, b)) => (strip(content), Some(content[a..b].to_string())),
        None => (content.to_string(), None),
    };
    let mut out = body.trim_end_matches(['\n', '\r']).to_string();
    if out.is_empty() {
        out.push_str("# AGENTS.md\n");
    }
    out.push_str("\n\n");
    out.push_str(&sync_block());
    if let Some(e) = env {
        out = apply(&out, &e);
    }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn apply_strip_roundtrip() {
        let info = EnvInfo {
            device: "office".into(),
            os: "Windows".into(),
            repos: vec![RepoEnv {
                name: "app".into(),
                mode: "bundle".into(),
                can_push: true,
            }],
            ..Default::default()
        };
        let orig = "# Rules\n\nBe nice.\n";
        let with = apply(orig, &render(&info));
        assert!(with.contains(ENV_BEGIN) && with.contains("office"));
        assert_eq!(strip(&with), orig);
        // Re-applying is idempotent.
        assert_eq!(apply(&with, &render(&info)), with);
        let synced = ensure_sync_block(&with).unwrap();
        assert!(synced.find(SYNC_BEGIN).unwrap() < synced.find(ENV_BEGIN).unwrap());
        assert!(ensure_sync_block(&synced).is_none());
        assert!(!strip(&synced).contains(ENV_BEGIN));
    }
}
